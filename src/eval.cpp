void init() {
  for (PieceType pt = P; pt <= K; ++pt) {
    for (Square sq = A1; sq <= H8; ++sq) {
      PSQT[make_piece(White, pt)][sq]            = BONUS[pt][sq] + PIECE_VALS[pt];
      PSQT[make_piece(Black, pt)][flip_rank(sq)] = -PSQT[make_piece(White, pt)][sq];
    }
  }
}

